"""Reproducible force completion matrix (Mission 4 §4).

Generates .dev/FORCE_COMPLETION_MATRIX.md directly from the live registries
(FORCE_DEFINITIONS + METHODOLOGY_REGISTRY + the same primary-classification
rule the /api/research/progress endpoint serves). No hand-maintained counts.

Run:  python scripts/generate_force_matrix.py
"""
from __future__ import annotations

import asyncio
import sys
from datetime import date
from pathlib import Path

if sys.platform == "win32":
    asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.cycle.force_definitions import FORCE_DEFINITIONS  # noqa: E402
from app.cycle.normalization_definitions import (  # noqa: E402
    CURRENT_MODEL_VERSION,
)
from app.cycle.force_aggregation_definitions import (  # noqa: E402
    FORCE_AGGREGATION_VERSION,
)
from app.research.methodology_registry import (  # noqa: E402
    MethodologyState,
    methods_for_force,
)

OUT = (
    Path(__file__).resolve().parents[3] / ".dev" / "FORCE_COMPLETION_MATRIX.md"
)


def _primary(fd, methods, approved) -> str:
    """Same mutually-exclusive rule as /api/research/progress."""
    if any(m.dimension == "level" for m in approved):
        return "level_published"
    if approved:
        return "dimension_only"
    if fd.live_indicator_codes or (fd.code == "geography" and methods):
        return "context_profile"
    return "deferred"


def main() -> None:
    rows: list[str] = []
    counts: dict[str, int] = {
        k: 0
        for k in (
            "level_published",
            "dimension_only",
            "context_profile",
            "deferred",
        )
    }
    for i, fd in enumerate(FORCE_DEFINITIONS, 1):
        methods = methods_for_force(fd.code)
        approved = [
            m for m in methods
            if m.state is MethodologyState.approved_production
        ]
        primary = _primary(fd, methods, approved)
        counts[primary] += 1
        dims = sorted({m.dimension for m in approved}) or ["—"]
        inputs = ", ".join(fd.live_indicator_codes) or "—"
        ceiling = fd.coverage_ceiling.value if fd.coverage_ceiling else "—"
        rows.append(
            f"| {i} | `{fd.code}` | {primary} | {', '.join(dims)} "
            f"| {ceiling} | {inputs} |"
        )

    total = sum(counts.values())
    lines = [
        "<!-- GENERATED by apps/api/scripts/generate_force_matrix.py — "
        "do not hand-edit; regenerate instead. -->",
        "",
        f"# Force completion matrix "
        f"({date.today().isoformat()}, {CURRENT_MODEL_VERSION.version_id} / "
        f"{FORCE_AGGREGATION_VERSION})",
        "",
        "Primary classes are mutually exclusive and sum to "
        f"{total}: "
        + " · ".join(f"{k} {v}" for k, v in counts.items())
        + " (same rule as /api/research/progress).",
        "",
        "| # | Force | Primary class | Published dimensions | Coverage ceiling"
        " | Live inputs |",
        "|---|-------|---------------|----------------------|-----------------"
        "|--------------|",
        *rows,
        "",
        "Legend: `level_published` = an approved level method publishes; "
        "`dimension_only` = approved non-level dimensions publish without a "
        "level; `context_profile` = live context data, no published "
        "dimensions; `deferred` = nothing functional. A `partial` ceiling "
        "means complete input data still cannot report 'available' — the "
        "mapped inputs are an explicitly incomplete proxy for the force.",
        "",
    ]
    content = "\n".join(lines)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            print(
                "FORCE_COMPLETION_MATRIX.md is stale — run "
                "scripts/generate_force_matrix.py"
            )
            sys.exit(1)
        print("FORCE_COMPLETION_MATRIX.md is up to date")
        return
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
